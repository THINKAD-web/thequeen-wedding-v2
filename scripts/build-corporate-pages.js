function updateHomePressPreview() {
  const indexPath = path.join(ROOT, 'index.html');
  let indexHtml = readFile(indexPath);
  const section = buildHomePressPreviewHtml();
  const markerRegex = /<!-- PRESS_PREVIEW_START -->[\s\S]*?<!-- PRESS_PREVIEW_END -->/;

  if (!markerRegex.test(indexHtml)) {
    indexHtml = indexHtml.replace(
      /(\s*)<!-- LATEST_POSTS_START -->/,
      `\n${section}\n$1<!-- LATEST_POSTS_START -->`,
    );
  } else {
    indexHtml = indexHtml.replace(markerRegex, section);
  }

  writeFile(indexPath, indexHtml);
  console.log('  ✓ index.html (press preview section)');
}

