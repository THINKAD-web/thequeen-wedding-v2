function readFile(filePath) {
  return fs.readFileSync(filePath, 'utf8');
}

function writeFile(filePath, content) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content, 'utf8');
}

function escapeHtml(str) {
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function replaceAll(template, vars) {
  let result = template;
  for (const [key, value] of Object.entries(vars)) {
    result = result.split(`{{${key}}}`).join(value ?? '');
  }
  return result;
}

function formatDateDisplay(dateStr) {
  if (!dateStr) return '';
  const d = new Date(dateStr);
  if (Number.isNaN(d.getTime())) return dateStr;
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${y}.${m}.${day}`;
}

function navActive(page) {
  return {
    NAV_ACTIVE_BANQUET: page === 'banquet' ? ' active' : '',
    NAV_ACTIVE_PARTNERS: page === 'partners' ? ' active' : '',
    NAV_ACTIVE_PRESS: page === 'press' ? ' active' : '',
  };
}

function renderPageShell(pageKey, meta, mainContent) {
  const template = readFile(path.join(TEMPLATES_DIR, 'corporate-page.html'));
  return replaceAll(template, {
    PAGE_TITLE: escapeHtml(meta.title),
    PAGE_DESCRIPTION: escapeHtml(meta.description),
    OG_TITLE: escapeHtml(meta.title),
    CANONICAL: meta.canonical,
    MAIN_CONTENT: mainContent,
    ...navActive(pageKey),
  });
}

