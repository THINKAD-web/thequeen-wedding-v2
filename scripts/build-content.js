marked.setOptions({ gfm: true, breaks: false });

function readFile(filePath) {
  return fs.readFileSync(filePath, 'utf8');
}

function writeFile(filePath, content) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content, 'utf8');
}

function escapeHtml(str) {
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function toAbsoluteUrl(url) {
  if (!url) return LOGO_URL;
  if (url.startsWith('http://') || url.startsWith('https://')) return url;
  return `${SITE_URL}${url.startsWith('/') ? '' : '/'}${url}`;
}

function formatDateDisplay(dateStr) {
  const d = new Date(dateStr);
  if (Number.isNaN(d.getTime())) return dateStr;
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${y}.${m}.${day}`;
}

function toRfc822(dateStr) {
  const d = new Date(dateStr);
  if (Number.isNaN(d.getTime())) return new Date().toUTCString();
  return d.toUTCString();
}

function replaceAll(template, vars) {
  let result = template;
  for (const [key, value] of Object.entries(vars)) {
    result = result.split(`{{${key}}}`).join(value ?? '');
  }
  return result;
}

function scanPosts() {
  const posts = [];

  function walk(dir) {
    if (!fs.existsSync(dir)) return;
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        walk(full);
      } else if (entry.isFile() && entry.name.endsWith('.md')) {
        const raw = readFile(full);
        const { data, content } = matter(raw);
        if (data.draft === true) continue;

        const category = data.category || path.basename(path.dirname(full));
        const slug = data.slug || entry.name.replace(/^\d{4}-\d{2}-\d{2}-/, '').replace(/\.md$/, '');

        posts.push({
          filePath: full,
          title: data.title || slug,
          description: data.description || '',
          date: String(data.date || '1970-01-01'),
          category,
          slug,
          thumbnail: data.thumbnail || LOGO_URL,
          keywords: data.keywords || [],
          content,
          htmlContent: marked.parse(content),
          url: `/${category}/${slug}`,
          canonical: `${SITE_URL}/${category}/${slug}`,
        });
      }
    }
  }

  walk(CONTENT_DIR);
  posts.sort((a, b) => new Date(b.date) - new Date(a.date));
  return posts;
}

function renderPostCard(post, options = {}) {
  const thumb = escapeHtml(toAbsoluteUrl(post.thumbnail));
  const href = escapeHtml(post.url);
  const title = escapeHtml(post.title);
  const desc = escapeHtml(post.description);
  const date = formatDateDisplay(post.date);
  const label = CATEGORY_LABELS[post.category] || post.category;

  return `
    <a href="${href}" class="card-lift group block overflow-hidden rounded-sm border border-[#0A2A5E]/10 bg-white shadow-md">
      <div class="aspect-video overflow-hidden bg-slate-100">
        <img src="${thumb}" alt="${title}" class="h-full w-full object-cover transition duration-500 group-hover:scale-105" loading="lazy">
      </div>
      <div class="p-5">
        <span class="text-[10px] font-semibold uppercase tracking-[0.2em] text-[#C9A96A]">${escapeHtml(label)}</span>
        <h3 class="mt-2 font-serif text-xl text-[#0A2A5E] line-clamp-2">${title}</h3>
        <time class="mt-2 block text-xs text-slate-500">${date}</time>
        ${options.showDescription !== false ? `<p class="mt-3 text-sm text-slate-600 line-clamp-2">${desc}</p>` : ''}
      </div>
    </a>`;
}

const STORY_TABS = [
  { key: 'news', href: '/news', label: '더퀸 소식' },
  { key: 'guide', href: '/guide', label: '웨딩 가이드' },
  { key: 'stories', href: '/stories', label: '리얼 웨딩' },
  { key: 'dining', href: '/dining', label: '퀸즈테이블' },
  { key: 'press', href: '/news/press', label: '언론보도' },
];

function renderCategoryTabs(activeKey) {
  return STORY_TABS.map((tab) => {
    const active = tab.key === activeKey ? 'active' : '';
    return `<a href="${tab.href}" class="tab-btn rounded-full border border-[#0A2A5E]/15 px-5 py-2 text-sm font-semibold text-[#0A2A5E] transition hover:border-[#C9A96A] ${active}">${tab.label}</a>`;
  }).join('\n    ');
}

function navForListCategory(category) {
  if (category === 'news') return renderDesktopNav('news');
  return renderDesktopNav(null);
}

function buildJsonLd(post) {
  const articleType = post.category === 'news' ? 'NewsArticle' : 'Article';
  const imageUrl = toAbsoluteUrl(post.thumbnail);

  const article = {
    '@context': 'https://schema.org',
    '@type': articleType,
    headline: post.title,
    description: post.description,
    image: imageUrl,
    datePublished: post.date,
    dateModified: post.date,
    author: { '@type': 'Organization', name: '더퀸 웨딩홀' },
    publisher: {
      '@type': 'Organization',
      name: '더퀸 웨딩홀',
      logo: { '@type': 'ImageObject', url: LOGO_URL },
    },
    mainEntityOfPage: post.canonical,
  };

  const breadcrumb = {
    '@context': 'https://schema.org',
    '@type': 'BreadcrumbList',
    itemListElement: [
      { '@type': 'ListItem', position: 1, name: '더퀸 웨딩홀', item: `${SITE_URL}/` },
      { '@type': 'ListItem', position: 2, name: CATEGORY_LABELS[post.category], item: `${SITE_URL}/${post.category}` },
      { '@type': 'ListItem', position: 3, name: post.title, item: post.canonical },
    ],
  };

  return JSON.stringify([article, breadcrumb]);
}

function renderRelatedPosts(post, allPosts) {
  const related = allPosts
    .filter((p) => p.category === post.category && p.slug !== post.slug)
    .slice(0, 3);

  if (related.length === 0) return '';

  const cards = related.map((p) => renderPostCard(p, { showDescription: false })).join('\n');

  return `
    <section class="mt-16 border-t border-[#C9A96A]/20 pt-12">
      <h2 class="mb-8 text-center font-serif text-2xl text-[#0A2A5E]">관련 글</h2>
      <div class="grid gap-6 sm:grid-cols-3 not-prose">${cards}</div>
    </section>`;
}

function renderPostExtra(post) {
  if (post.slug !== 'queens-table-five-star') return '';
  return `
    <div class="mx-auto max-w-3xl mt-12 rounded-sm border border-[#C9A96A]/30 bg-gradient-to-br from-[#FAF6EC] to-white p-6 text-center not-prose">
      <p class="text-sm text-slate-600">기업·단체 연회와 케이터링도 같은 건물에서 상담하실 수 있습니다.</p>
      <a href="/banquet" class="mt-4 inline-flex items-center rounded-full bg-gradient-to-r from-[#0A2A5E] to-[#1E4A8C] px-6 py-2.5 text-sm font-semibold text-white shadow-md hover:-translate-y-0.5 transition">기업·단체 연회 · 케이터링 안내</a>
    </div>`;
}

function generatePostPages(posts) {
  const postTemplate = readFile(path.join(TEMPLATES_DIR, 'post.html'));

  for (const post of posts) {
    const html = replaceAll(postTemplate, {
      DESKTOP_NAV: renderDesktopNav('news'),
      SITE_FOOTER: SITE_FOOTER_HTML,
      TITLE: escapeHtml(post.title),
      DESCRIPTION: escapeHtml(post.description),
      CANONICAL: post.canonical,
      OG_IMAGE: toAbsoluteUrl(post.thumbnail),
      JSON_LD: buildJsonLd(post),
      CATEGORY: post.category,
      CATEGORY_LABEL: CATEGORY_LABELS[post.category],
      CATEGORY_TABS: renderCategoryTabs(post.category),
      DATE_ISO: post.date,
      DATE_DISPLAY: formatDateDisplay(post.date),
      HERO_IMAGE: post.thumbnail
        ? `<div class="mx-auto max-w-3xl overflow-hidden rounded-sm"><img src="${escapeHtml(toAbsoluteUrl(post.thumbnail))}" alt="${escapeHtml(post.title)}" class="w-full object-cover" loading="eager"></div>`
        : '',
      CONTENT: post.htmlContent,
      POST_EXTRA: renderPostExtra(post),
      RELATED_POSTS: renderRelatedPosts(post, posts),
      TITLE_JS: JSON.stringify(post.title),
      DESCRIPTION_JS: JSON.stringify(post.description),
      OG_IMAGE_JS: JSON.stringify(toAbsoluteUrl(post.thumbnail)),
      CANONICAL_JS: JSON.stringify(post.canonical),
      KAKAO_JS_KEY: JSON.stringify(KAKAO_JS_KEY),
    });

    const outPath = path.join(ROOT, post.category, `${post.slug}.html`);
    writeFile(outPath, html);
    console.log(`  ✓ ${post.category}/${post.slug}.html`);
  }
}

