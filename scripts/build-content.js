function generateSitemap(posts) {
  const urls = [...BASE_SITEMAP_URLS];

  for (const category of CATEGORIES) {
    urls.push({
      loc: `${SITE_URL}/${category}`,
      changefreq: 'weekly',
      priority: '0.8',
    });
  }

  for (const post of posts) {
    urls.push({
      loc: post.canonical,
      changefreq: 'monthly',
      priority: '0.7',
      lastmod: post.date,
    });
  }

  const urlEntries = urls.map((u) => {
    let entry = `  <url>\n    <loc>${escapeHtml(u.loc)}</loc>\n`;
    if (u.lastmod) entry += `    <lastmod>${u.lastmod}</lastmod>\n`;
    entry += `    <changefreq>${u.changefreq}</changefreq>\n    <priority>${u.priority}</priority>\n  </url>`;
    return entry;
  }).join('\n');

  const xml = `<?xml version="1.0" encoding="UTF-8"?>\n${AUTO_COMMENT}<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"\n        xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">\n${urlEntries}\n</urlset>\n`;

  writeFile(path.join(ROOT, 'sitemap.xml'), xml);
  console.log(`  ✓ sitemap.xml (${urls.length} URLs)`);
}

function generateRss(posts) {
  const items = posts.slice(0, 20).map((post) => `    <item>
      <title>${escapeHtml(post.title)}</title>
      <link>${post.canonical}</link>
      <description>${escapeHtml(post.description)}</description>
      <pubDate>${toRfc822(post.date)}</pubDate>
      <guid isPermaLink="true">${post.canonical}</guid>
    </item>`).join('\n');

  const xml = `<?xml version="1.0" encoding="UTF-8"?>\n${AUTO_COMMENT}<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
  <channel>
    <title>더퀸 웨딩홀 스토리</title>
    <link>${SITE_URL}</link>
    <description>더퀸 웨딩홀의 소식, 웨딩 가이드, 리얼 웨딩, 퀸즈테이블 이야기</description>
    <language>ko</language>
    <atom:link href="${SITE_URL}/rss.xml" rel="self" type="application/rss+xml"/>
${items}
  </channel>
</rss>\n`;

  writeFile(path.join(ROOT, 'rss.xml'), xml);
  console.log(`  ✓ rss.xml (${Math.min(posts.length, 20)} items)`);
}

async function main() {
  console.log('Building content...\n');

  const basePosts = scanPosts();
  console.log(`Found ${basePosts.length} published post(s)\n`);

  console.log('Generating post pages:');
  generatePostPages(basePosts);

  const { buildSeasonal } = require('./build-seasonal');
  let seasonalCtx = { seasonalPosts: [], renderSeasonalListCard: null, storiesInstagramBar: '' };
  try {
    seasonalCtx = await buildSeasonal();
  } catch (err) {
    console.error(err);
  }

  const allPosts = mergeSeasonalPosts(
    basePosts,
    seasonalCtx.seasonalPosts,
    seasonalCtx.renderSeasonalListCard,
  );
  finishBuild(basePosts, allPosts, seasonalCtx);
}

function finishBuild(basePosts, allPosts, seasonalCtx) {
  console.log('\nGenerating list pages:');
  generateListPages(basePosts, seasonalCtx);
  generatePressListPage();

  console.log('\nUpdating home page:');
  updateHomeLatestPosts(allPosts);

  console.log('\nGenerating feeds:');
  generateSitemap(allPosts);
  generateRss(allPosts);

  const { buildCorporatePages } = require('./build-corporate-pages');
  buildCorporatePages();

  const { patchIndexNav } = require('./patch-index-nav');
  console.log('\nPatching home navigation:');
  patchIndexNav();

  const { applySharedNav } = require('./apply-shared-nav');
  applySharedNav();

  const { applyLegacyLayout, ensureMicroHomeLinks } = require('./build-shared-layout');
  applyLegacyLayout();
  ensureMicroHomeLinks();

  const { patchQueensBoxContent } = require('./patch-queens-box-content');
  patchQueensBoxContent();

  const { applySiteFooters } = require('./apply-site-footers');
  applySiteFooters();

  console.log('\nDone.');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
